#!/usr/bin/env python3
"""Artifact colour test cartridges for the NTSC 7800.

    python tools/artifacttest.py build [-o artifacttest] [--fg 0x0F] [--fg2 0x84]
    python tools/artifacttest.py shoot [-o artifacttest] [--mame PATH]

`build` writes artifacttest-7800.a78 (signed with sign7800.py, so a real NTSC
console runs it through Atari's BIOS; .bin without the header, .asm beside it).
It draws twelve bands of one-byte patterns repeated across the line in 320A
mode, on black: bands 1-8 in the foreground colour (default $0F, white),
9-12 in a second one (default $84, a mid blue, as Tower Toppler mixes colour
and pattern). A 320 pixel is one MARIA clock, half a cycle of the colour
carrier, so a pattern that fine reaches a composite TV as colour that no
palette entry has: the colour Tower Toppler draws its tower with, and what
MAME's Composite Video setting makes.

Each band has its number on its left as that many short blocks, then the
pattern:

     1  $AA  10101010   one on, one off: the carrier itself
     2  $55  01010101   the same a pixel later: the opposite hue
     3  $88  10001000   one on in four
     4  $44  01000100   the same a pixel later: band 3's opposite
     5  $EE  11101110   three on in four: lighter, band 3's hue turned half
     6  $77  01110111   and band 4's
     7  $CC  11001100   two on, two off: half the carrier, little colour
     8  $FF  solid      the foreground, for reference
     9  $AA             bands 1, 2, 3 and 8 in the second colour
    10  $55
    11  $88
    12  $FF

A one-pixel shift is half a carrier cycle, so each pattern has two hues, half
a turn apart (1 against 2, 3 against 4), and a two-pixel shift changes
nothing. Through RGB, S-video or an emulator's palette all of them are plain
stripes.

What to look for. On a composite or RF TV, band 1's hue says where MARIA's
pixels sit against the carrier, which is MAME's Composite Artifact Phase
setting: with the warm palette, MAME's band 1 is blue at phase 0, purple at
1, gold at 2 and green at 3, and band 2 the hue opposite. A console's photo
picks the phase. A TV's tint control and the console's temperature (the warm,
cool and hot palettes) turn every hue together, plain colours included, so
compare band 1 against band 8's and 12's plain colours, not on its own.

`build` also writes artifacthues-7800.a78, the same question across the
palette: on a console the patterns in a colour do not decode as MiSTer's
model (and so MAME) has them (artifacttest's bands 9-10: $AA in blue shows
nearly the solid blue, $55 a bright magenta, where the model has a dark violet
and a dark teal), and fitting a better model needs the colour codes' answers
one by one. Sixteen rows, hue $0 at the top to hue $F at the bottom (a short
white tick at the left marks rows 0, 4, 8 and 12), each with nine blocks:

    luminance 4:  solid  $AA  $55     luminance 8:  solid  $AA  $55
    luminance C:  solid  $AA  $55

24 pixels each, on black. A display list interrupt on the middle of the three
black lines before each row loads the row's three colours (palettes 0-2,
colour 2); it writes them just after a WSYNC, in horizontal blank, since a
colour register write shows as a repeated pixel where the beam is. Hue
$0's row is grey, the plain pattern colours for reference. Photograph it
straight on, with the TV's tint, colour and brightness controls where they
were for artifacttest, and the whole screen in the picture.

`shoot` takes MAME's pictures of both cartridges with Composite Video off,
then on at each artifact phase, as PNGs in the output folder.
"""
import argparse
import os
import struct
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

# (pattern, palette): palette 0 is the foreground, 1 the second colour
BANDS = [(0xAA, 0), (0x55, 0), (0x88, 0), (0x44, 0), (0xEE, 0), (0x77, 0), (0xCC, 0), (0xFF, 0),
         (0xAA, 1), (0x55, 1), (0x88, 1), (0xFF, 1)]
BAND_LINES = 12         # a band is one zone this tall ...
GAP_LINES = 4           # ... and a blank zone after it
TOP_LINES = 24          # blank zones before the first band (MAME shows lines 27-250)
PAT_BYTES = 24          # 192 pixels of pattern, from hpos 52 (320 pixel 104)
PAT_HPOS = 52
KEY_HPOS = 2            # the number: up to 12 bytes of $F0 from hpos 2 (ends at 50)
PAGES = {0: 0xC0, 1: 0xD0}      # the band patterns, 8 bands a page group
KEY_PAGE = 0xE0                 # the number's blocks


def source(fg=0x0F, fg2=0x84):
    L = []
    a = L.append
    a("; 7800 artifact colour test -- generated by artifacttest.py")
    a("; 12 bands of 320A patterns, in $%02X and $%02X on black; see the .py for the key." % (fg, fg2))
    a("INPTCTRL   = $01")
    a("BACKGRND   = $20")
    a("P0C2       = $22")
    a("P1C2       = $26")
    a("MSTAT      = $28")
    a("DPPH       = $2C")
    a("DPPL       = $30")
    a("OFFSET     = $38")
    a("CTRL       = $3C")
    a("")
    a("    .org $C000")
    a("; A zone reads page (high byte + offset) on each line, the offset counting")
    a("; down to 0, so a %d-line band zone pointed at page P reads P+%d ... P." % (BAND_LINES, BAND_LINES - 1))
    a("; Those pages are all alike: band k's pattern at (k mod 8) * 32 in group")
    a("; $C0 (bands 1-8) or $D0 (9-12), and $F0 blocks for the number at $E0.")
    for page in range(0xC0, 0x100 - 0x10):
        group, sub = page & 0xF0, page & 0x0F
        a("gfx_%02X:" % page)
        if sub >= BAND_LINES:
            a("    .res 256,$00")
        elif group in PAGES.values():
            g = [k for k, v in PAGES.items() if v == group][0]
            for slot in range(8):
                k = g * 8 + slot
                if k < len(BANDS):
                    a("    .byte " + ",".join(["$%02X" % BANDS[k][0]] * PAT_BYTES))
                    a("    .res %d,$00" % (32 - PAT_BYTES))
                else:
                    a("    .res 32,$00")
        else:                           # KEY_PAGE
            a("    .byte " + ",".join(["$F0"] * 16))
            a("    .res 240,$00")
    a("")
    a("reset:")
    a("    SEI")
    a("    CLD")
    a("    LDA #$17")
    a("    STA INPTCTRL")
    a("    LDA #$00")
    a("    STA OFFSET")
    a("    STA INPTCTRL")
    a("    LDX #$FF")
    a("    TXS")
    a("    LDA #$60                  ; DMA off while setting up")
    a("    STA CTRL")
    a("    LDA #$00")
    a("    STA BACKGRND")
    a("    LDA #$%02X" % fg)
    a("    STA P0C2                  ; 320A draws colour 2 of the palette")
    a("    LDA #$%02X" % fg2)
    a("    STA P1C2")
    a("    LDA #>dll")
    a("    STA DPPH")
    a("    LDA #<dll")
    a("    STA DPPL")
    a("start_low:")
    a("    BIT MSTAT")
    a("    BMI start_low")
    a("start_high:")
    a("    BIT MSTAT")
    a("    BPL start_high")
    a("    LDA #$43                  ; DMA on, 320A/C, colour on, black border")
    a("    STA CTRL")
    a("forever:")
    a("    JMP forever")
    a("")
    a("nmi:")
    a("irq:")
    a("    RTI")
    a("")
    a("dl_empty:")
    a("    .byte $00,$00")
    for k, (pat, pal) in enumerate(BANDS):
        group = PAGES[k // 8]
        a("dl_band_%d:                     ; band %d, $%02X in palette %d" % (k + 1, k + 1, pat, pal))
        a("    .byte $00,$%02X,$%02X,$%02X     ; the number: %d blocks"
          % ((32 - (k + 1)) & 0x1F, KEY_PAGE, KEY_HPOS, k + 1))
        a("    .byte $%02X,$%02X,$%02X,$%02X     ; the pattern, %d bytes"
          % ((k % 8) * 32, (pal << 5) | ((32 - PAT_BYTES) & 0x1F), group, PAT_HPOS, PAT_BYTES))
        a("    .byte $00,$00")
    a("")
    a("dll:")

    def blank(n):
        while n > 0:
            m = min(n, 16)
            a("    .byte $%02X,>dl_empty,<dl_empty" % (m - 1))
            n -= m
    blank(TOP_LINES)
    for k in range(len(BANDS)):
        a("    .byte $%02X,>dl_band_%d,<dl_band_%d" % (BAND_LINES - 1, k + 1, k + 1))
        blank(GAP_LINES)
    blank(160)
    a("")
    a("code_end:")
    a("    .res $FF80-code_end,$FF")
    a("    .res $78,$FF                  ; the signature ($FF80-$FFF7)")
    a("    .byte $FF                     ; $FFF8: region byte")
    a("    .byte $C7                     ; $FFF9: hashed from $C000, no rainbow")
    a("    .word nmi")
    a("    .word reset")
    a("    .word irq")
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- the hue rows
HUE_ROW_LINES = 9       # a row: a zone this tall, after 3 black lines, the middle with the interrupt
HUE_TOP_LINES = 20
HUE_LUMS = (0x4, 0x8, 0xC)
HUE_PATS = (0xFF, 0xAA, 0x55)
HUE_BLOCK_BYTES = 3     # 24 pixels
HUE_HPOS0 = 8           # the first block's hpos; blocks every 16 (32 pixels)
HUE_PITCH = 16
HUE_PAGE = 0xC0         # pages $C0-$C8: solid at $00, $AA at $04, $55 at $08, the tick ($F0) at $0C


def source_hues():
    L = []
    a = L.append
    a("; 7800 artifact colour test, every hue -- generated by artifacttest.py")
    a("; 16 rows (hue $0-$F); in each, luminance 4, 8, C: solid, $AA, $55 in 320A.")
    a("INPTCTRL   = $01")
    a("BACKGRND   = $20")
    a("P0C2       = $22")
    a("P1C2       = $26")
    a("P2C2       = $2A")
    a("WSYNC      = $24")
    a("MSTAT      = $28")
    a("DPPH       = $2C")
    a("DPPL       = $30")
    a("OFFSET     = $38")
    a("CTRL       = $3C")
    a("P7C2       = $3E")
    a("ROW        = $40        ; the row the next interrupt colours")
    a("")
    a("    .org $C000")
    a("; A %d-line row zone pointed at $%02X reads pages $%02X ... $%02X, all alike."
      % (HUE_ROW_LINES, HUE_PAGE, HUE_PAGE + HUE_ROW_LINES - 1, HUE_PAGE))
    for page in range(HUE_PAGE, 0xF0):
        a("gfx_%02X:" % page)
        if page - HUE_PAGE < HUE_ROW_LINES:
            for pat in HUE_PATS:
                a("    .byte " + ",".join(["$%02X" % pat] * HUE_BLOCK_BYTES) + ",$00")
            a("    .byte $F0")
            a("    .res 256-13,$00")
        else:
            a("    .res 256,$00")
    a("")
    a("reset:")
    a("    SEI")
    a("    CLD")
    a("    LDA #$17")
    a("    STA INPTCTRL")
    a("    LDA #$00")
    a("    STA OFFSET")
    a("    STA INPTCTRL")
    a("    LDX #$FF")
    a("    TXS")
    a("    LDA #$60                  ; DMA off while setting up")
    a("    STA CTRL")
    a("    LDA #$00")
    a("    STA BACKGRND")
    a("    STA ROW")
    a("    LDA #$0F")
    a("    STA P7C2                  ; the ticks")
    a("    LDA #>dll")
    a("    STA DPPH")
    a("    LDA #<dll")
    a("    STA DPPL")
    a("start_low:")
    a("    BIT MSTAT")
    a("    BMI start_low")
    a("start_high:")
    a("    BIT MSTAT")
    a("    BPL start_high")
    a("    LDA #$43                  ; DMA on, 320A/C, colour on, black border")
    a("    STA CTRL")
    a("main:")
    a("    BIT MSTAT")
    a("    BMI main                  ; wait for the picture")
    a("wait_vblank:")
    a("    BIT MSTAT")
    a("    BPL wait_vblank")
    a("    LDA #$00")
    a("    STA ROW")
    a("    JMP main")
    a("")
    a("; One interrupt a row: hue ROW at luminance 4, 8 and C into P0C2, P1C2, P2C2.")
    a("; The colours are worked out first and written just after a WSYNC, in the next")
    a("; line's horizontal blank, so the writes never show (a write repeats a pixel).")
    a("nmi:")
    a("    PHA")
    a("    TXA")
    a("    PHA")
    a("    TYA")
    a("    PHA")
    a("    LDA ROW")
    a("    ASL")
    a("    ASL")
    a("    ASL")
    a("    ASL")
    a("    ORA #$%02X" % HUE_LUMS[1])
    a("    TAX")
    a("    EOR #$%02X" % (HUE_LUMS[1] ^ HUE_LUMS[2]))
    a("    TAY")
    a("    EOR #$%02X" % (HUE_LUMS[2] ^ HUE_LUMS[0]))
    a("    STA WSYNC")
    a("    STA P0C2")
    a("    STX P1C2")
    a("    STY P2C2")
    a("    INC ROW")
    a("    PLA")
    a("    TAY")
    a("    PLA")
    a("    TAX")
    a("    PLA")
    a("irq:")
    a("    RTI")
    a("")
    a("dl_empty:")
    a("    .byte $00,$00")
    for mark in (False, True):
        a("dl_row%s:" % ("_mark" if mark else ""))
        if mark:
            a("    .byte $0C,$%02X,$%02X,$00     ; the tick: palette 7, 1 byte, x 0"
              % ((7 << 5) | 31, HUE_PAGE))
        for i, lum in enumerate(HUE_LUMS):
            for j, pat in enumerate(HUE_PATS):
                a("    .byte $%02X,$%02X,$%02X,$%02X     ; luminance %X, $%02X: palette %d"
                  % (4 * j, (i << 5) | ((32 - HUE_BLOCK_BYTES) & 0x1F), HUE_PAGE,
                     HUE_HPOS0 + HUE_PITCH * (3 * i + j), lum, pat, i))
        a("    .byte $00,$00")
    a("")
    a("dll:")

    def blank(n):
        while n > 0:
            m = min(n, 16)
            a("    .byte $%02X,>dl_empty,<dl_empty" % (m - 1))
            n -= m
    blank(HUE_TOP_LINES)
    for r in range(16):
        a("    .byte $00,>dl_empty,<dl_empty    ; row %X: 3 black lines, the middle one" % r)
        a("    .byte $80,>dl_empty,<dl_empty    ; with the interrupt")
        a("    .byte $00,>dl_empty,<dl_empty")
        lbl = "dl_row_mark" if r % 4 == 0 else "dl_row"
        a("    .byte $%02X,>%s,<%s" % (HUE_ROW_LINES - 1, lbl, lbl))
    blank(160)
    a("")
    a("code_end:")
    a("    .res $FF80-code_end,$FF")
    a("    .res $78,$FF                  ; the signature ($FF80-$FFF7)")
    a("    .byte $FF                     ; $FFF8: region byte")
    a("    .byte $C7                     ; $FFF9: hashed from $C000, no rainbow")
    a("    .word nmi")
    a("    .word reset")
    a("    .word irq")
    return "\n".join(L) + "\n"


def _write(outdir, name, src, title):
    import asm
    import colortest
    import sign7800
    open(os.path.join(outdir, name + ".asm"), "w").write(src)
    rom = asm.Assembler().assemble(src.splitlines())
    assert len(rom) == 0x4000, len(rom)
    rom = sign7800.signed(rom)
    assert sign7800.verify(rom)
    path = os.path.join(outdir, name + ".a78")
    open(path, "wb").write(colortest.a78_header(len(rom), title, False) + rom)
    open(path[:-4] + ".bin", "wb").write(rom)
    return path


def build(outdir, fg=0x0F, fg2=0x84):
    os.makedirs(outdir, exist_ok=True)
    return [_write(outdir, "artifacttest-7800", source(fg, fg2), "Artifact colour test"),
            _write(outdir, "artifacthues-7800", source_hues(), "Artifact colour test, hues")]


SHOOT_LUA = """
local f = 0
local comp = tonumber(os.getenv("ARTIFACT_COMPOSITE") or "0")
local phase = tonumber(os.getenv("ARTIFACT_PHASE") or "1")
emu.register_frame_done(function()
  f = f + 1
  if f == 1 then
    local p = manager.machine.ioport.ports[":COMPOSITE"]
    if p then
      p.fields["Composite Video"].user_value = comp
      p.fields["Composite Artifact Phase"].user_value = phase * 32
    elseif comp ~= 0 then
      print("NO COMPOSITE SETTING")
    end
  end
  if f == 240 then manager.machine.video:snapshot() end
  if f >= 241 then manager.machine:exit() end
end)
"""


def shoot(outdir, mame=None, bios=None):
    import capture
    exe = capture.find_mame(mame)
    if not exe:
        sys.exit("MAME was not found: pass --mame or set A7800_MAME")
    work = tempfile.mkdtemp(prefix="artifacttest-")
    lua = os.path.join(work, "shoot.lua")
    open(lua, "w").write(SHOOT_LUA)
    made = []
    shots = [(0, 1, "palette")] + [(1, p, "composite-phase%d" % p) for p in range(4)]
    for cart, (comp, phase, what) in [(c, sh) for c in ("artifacttest", "artifacthues") for sh in shots]:
        rom = os.path.abspath(os.path.join(outdir, cart + "-7800.a78"))
        if not os.path.isfile(rom):
            sys.exit("%s is missing: run `build` first" % rom)
        name = "mame-%s-%s" % (cart, what)
        snaps = os.path.join(work, name)
        env = dict(os.environ, ARTIFACT_COMPOSITE=str(comp), ARTIFACT_PHASE=str(phase))
        out = subprocess.run([exe, "a7800", "-cart", rom, "-video", "none", "-sound", "none", "-nothrottle",
                              "-skip_gameinfo", "-snapshot_directory", snaps, "-snapname", "snap",
                              "-cfg_directory", os.path.join(work, "cfg"), "-autoboot_script", lua]
                             + capture.bios_args(bios), stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                             cwd=work, env=env, timeout=300).stdout.decode("utf-8", "replace")
        if "NO COMPOSITE SETTING" in out:
            sys.exit("this MAME has no Composite Video setting (it came with the patched MAME in November 2026)")
        src = os.path.join(snaps, "snap.png")
        if not os.path.isfile(src):
            sys.exit("MAME made no picture:\n" + out[-2000:])
        dst = os.path.join(outdir, name + ".png")
        os.replace(src, dst)
        made.append(dst)
    return made


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build", help="write the cartridges")
    b.add_argument("-o", "--outdir", default="artifacttest")
    b.add_argument("--fg", type=lambda s: int(s, 0), default=0x0F,
                   help="bands 1-8's colour code (default 0x0F, white)")
    b.add_argument("--fg2", type=lambda s: int(s, 0), default=0x84,
                   help="bands 9-12's colour code (default 0x84, blue)")
    s = sub.add_parser("shoot", help="MAME's pictures: the palette, and Composite Video at each phase")
    s.add_argument("-o", "--outdir", default="artifacttest")
    s.add_argument("--mame")
    s.add_argument("--bios", help="-bios for the 7800 (default: A7800_BIOS, else MAME's default)")
    args = ap.parse_args(argv)
    if args.cmd == "build":
        for p in build(args.outdir, args.fg, args.fg2):
            print(p)
    else:
        for p in shoot(args.outdir, args.mame, args.bios):
            print(p)


if __name__ == "__main__":
    main()

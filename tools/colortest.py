#!/usr/bin/env python3
"""Colour test cartridges for the 2600 and 7800, and a tool to compare screenshots of them.

    python tools/colortest.py build [-o colortest]
    python tools/colortest.py shoot [-o colortest] [--mame PATH]
    python tools/colortest.py compare reference.png mame.png [-o report.png]

`build` writes four cartridges that put every colour of the machine on screen at
once, in a grid, and hold it there:

    colortest-2600-ntsc.a26    128 colours: 16 hues down, 8 luminances across
    colortest-2600-pal.a26     the same codes with PAL timing (312 lines)
    colortest-7800-ntsc.a78    256 colours: 16 hues down, 16 luminances across
                               (signed with sign7800.py, so a real NTSC console
                               runs it through Atari's BIOS; .bin without header)
    colortest-7800-pal.a78     the same codes on a PAL 7800

Row r is hue r (colour codes $r0, $r2, ... on the 2600, $r0, $r1, ... on the
7800), so the grid is the palette in code order: top left is $00, the end of
the first row is the brightest grey, the bottom right is $FE / $FF. A white
bar above and a white bar below mark the grid, which is how `compare` finds it
in a screenshot of any size, with any border.

Run them on the renderer you trust (an FPGA core, real hardware through a
capture card, Stella, another emulator), screenshot the screen *without* CRT
shaders or scanline effects, and compare that with MAME's picture of the same
cartridge (`shoot` takes those, in MAME, as PNGs):

    python tools/colortest.py compare stella-2600.png colortest/mame-2600-ntsc.png

`compare` reads each cell's middle (a median, so dot crawl and a sharp edge do
not move it), prints both colours and the difference for every code, lists the
worst, and draws a picture with each cell split: the reference on the left,
the other on the right. `--json` writes the reference palette it read, code by
code, which is what a palette fix would start from.

How the screens are drawn, so a strange result can be told from a broken test:

* 2600: the background colour is rewritten eight times along each line, five
  CPU cycles apart (STA COLUBK / ADC #2), from a fixed cycle after WSYNC. The
  cells are 15 colour clocks wide and the bars are drawn by the same code, so
  they span the cells exactly.
* 7800: each row is a zone of sixteen 8-pixel objects, one per luminance, using
  palettes 0-5. A display-list interrupt loads the row's sixteen colours into
  those palettes. It is armed on a 3-line empty zone before each row, and the
  zone either side of it is black too, so the palette change lands in four
  black lines whichever line a renderer raises the interrupt on.
* Both: every row is 11 lines, 6 of them coloured; the grid with its bars is
  187 lines tall (see GEOMETRY), the same on both machines.
"""
import argparse
import json
import os
import struct
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

# ------------------------------------------------------------------ geometry
# In scanlines from the top of the upper bar. Lines 0-3 are the upper bar,
# row r's colour is on lines 8+11r .. 13+11r, and the lower bar is 183-186.
GEOMETRY = {
    "bar": 4,
    "row_pitch": 11,
    "row_first": 8,         # first coloured line of row 0
    "row_lines": 6,
    "total": 187,           # upper bar to the end of the lower bar
}

MACHINES = {
    # name: (columns, file, MAME system)
    "2600-ntsc": (8, "colortest-2600-ntsc.a26", "a2600"),
    "2600-pal": (8, "colortest-2600-pal.a26", "a2600p"),
    "7800-ntsc": (16, "colortest-7800-ntsc.a78", "a7800"),
    "7800-pal": (16, "colortest-7800-pal.a78", "a7800p"),
}


# ---------------------------------------------------------------- 2600 source
def source_2600(pal):
    # Lines per frame: 3 VSYNC + VBL + visible + overscan (262 NTSC, 312 PAL).
    # The grid uses 188 visible lines (its 187 and the black line after the
    # lower bar); the rest is split above and below it.
    vbl, visible, overscan = (45, 228, 36) if pal else (33, 200, 26)
    top = (visible - 188) // 2
    bottom = visible - 188 - top
    L = []
    a = L.append
    a("; 2600 colour test (%s) -- generated by colortest.py" % ("PAL" if pal else "NTSC"))
    a("; 16 rows (hue $0-$F) x 8 columns (luminance 0,2,...,E), bars above and below.")
    a("VSYNC      = $00")
    a("VBLANK     = $01")
    a("WSYNC      = $02")
    a("COLUBK     = $09")
    a("HUE        = $80        ; this row's hue, $00-$F0")
    a("BARCOL     = $81        ; $0E: read like HUE, so the bar lines keep the grid's timing")
    a("")
    a("    .org $F000")
    a("reset:")
    a("    SEI")
    a("    CLD")
    a("    LDX #$FF")
    a("    TXS")
    a("    LDA #$00")
    a("clear:")
    a("    STA $00,X")
    a("    DEX")
    a("    BNE clear")
    a("    LDA #$0E")
    a("    STA BARCOL")
    a("")
    a("frame:")
    a("    LDA #$02")
    a("    STA VBLANK")
    a("    STA WSYNC")
    a("    STA VSYNC")
    a("    STA WSYNC")
    a("    STA WSYNC")
    a("    STA WSYNC")
    a("    LDA #$00")
    a("    STA VSYNC")
    a("    LDX #%d" % (vbl - 1))
    a("vblank:")
    a("    STA WSYNC")
    a("    DEX")
    a("    BNE vblank")
    a("    LDA #$00")
    a("    STA VBLANK")
    a("")
    a("    ; Every routine draws one line per WSYNC. grid and bar end their last")
    a("    ; line too late to return inside it, so each leaves one more line,")
    a("    ; black (COLUBK is 0 by then): the 1 black line under every row.")
    a("    LDX #%d" % top)
    a("    JSR black")
    a("    LDX #4")
    a("    JSR bar                   ; 4 white + 1 black")
    a("    LDX #3")
    a("    JSR black")
    a("    LDA #$00")
    a("    STA HUE")
    a("row:")
    a("    LDX #6")
    a("    JSR grid                  ; 6 colour + 1 black")
    a("    LDA HUE")
    a("    CLC")
    a("    ADC #$10")
    a("    STA HUE")
    a("    BEQ rows_done             ; past hue $F")
    a("    LDX #4")
    a("    JSR black")
    a("    JMP row")
    a("rows_done:")
    a("    LDX #3")
    a("    JSR black")
    a("    LDX #4")
    a("    JSR bar")
    a("    LDX #%d" % bottom)
    a("    JSR black")
    a("    LDA #$02")
    a("    STA VBLANK")
    a("    LDX #%d" % overscan)
    a("overscan:")
    a("    STA WSYNC")
    a("    DEX")
    a("    BNE overscan")
    a("    JMP frame")
    a("")
    a("black:")
    a("    STA WSYNC")
    a("    DEX")
    a("    BNE black")
    a("    RTS")
    a("")
    for name, var, step in (("grid", "HUE", 2), ("bar", "BARCOL", 0)):
        a("%s:" % name)
        a("    STA WSYNC                 ; cycle 0")
        a("    LDA %s                   ; 3" % var)
        a("    CLC                       ; 5")
        for _ in range(9):
            a("    NOP")
        a("    STA COLUBK                ; written on cycle 26: x = 10")
        for _ in range(7):
            a("    ADC #$%02X" % step)
            a("    STA COLUBK                ; every 5 cycles: 15 colour clocks a cell")
        a("    LDA #$00")
        a("    STA COLUBK                ; cycle 66")
        a("    DEX")
        a("    BNE %s" % name)
        a("    RTS")
        a("")
    a("code_end:")
    a("    .res $FFFC-code_end,$FF")
    a("    .word reset")
    a("    .word reset")
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- 7800 source
GFX_PAGE = 0xC0     # zone pages $C0-$C7; $C1-$C6 hold the patterns, $C0 and $C7 are blank


def source_7800(pal):
    # The zone list starts at MARIA's first DMA line; the grid is placed so it
    # sits in the middle of what MAME shows (lines 27-250 NTSC, 35-294 PAL).
    top = 54 if pal else 30
    regs = [0x21 + 4 * (c // 3) + c % 3 for c in range(16)]     # P0C1 ... P5C1
    L = []
    a = L.append
    a("; 7800 colour test (%s) -- generated by colortest.py" % ("PAL" if pal else "NTSC"))
    a("; 16 rows (hue $0-$F) x 16 columns (luminance $0-$F), bars above and below.")
    a("INPTCTRL   = $01")
    a("BACKGRND   = $20")
    a("MSTAT      = $28")
    a("DPPH       = $2C")
    a("DPPL       = $30")
    a("OFFSET     = $38")
    a("CTRL       = $3C")
    a("P7C3       = $3F")
    a("ROW        = $40        ; the row the next interrupt colours")
    a("")
    a("    .org $C000")
    a("; Zone graphics. A zone reads page (high byte + offset) on each line, the")
    a("; offset counting down to 0, so an 8-line row zone pointed at $C0 reads")
    a("; $C7 (blank), $C6-$C1 (colour) and $C0 (blank); a 4-line bar zone pointed")
    a("; at $C1 reads $C4-$C1. Each pattern page: $55 $55 (colour 1), $AA $AA")
    a("; (colour 2), $FF $FF (colour 3) at $00-$05, and 20 bytes of $FF at $10")
    a("; for the bar.")
    for page in range(8):
        a("gfx_%X:" % (GFX_PAGE + page))
        if 1 <= page <= 6:
            a("    .byte $55,$55,$AA,$AA,$FF,$FF")
            a("    .res 10,$00")
            a("    .byte " + ",".join(["$FF"] * 20))
            a("    .res 256-36,$00")
        else:
            a("    .res 256,$00")
    a("")
    a("reset:")
    a("    SEI")
    a("    CLD")
    a("    LDA #$17")
    a("    STA INPTCTRL")
    a("    LDA #$00")
    a("    STA OFFSET")
    a("    STA INPTCTRL")
    a("    LDX #$FF")
    a("    TXS")
    a("    LDA #$60                  ; DMA off while setting up")
    a("    STA CTRL")
    a("    LDA #$00")
    a("    STA BACKGRND")
    a("    STA ROW")
    a("    LDA #$0F")
    a("    STA P7C3                  ; the bars")
    a("    LDA #>dll")
    a("    STA DPPH")
    a("    LDA #<dll")
    a("    STA DPPL")
    a("start_low:")
    a("    BIT MSTAT")
    a("    BMI start_low")
    a("start_high:")
    a("    BIT MSTAT")
    a("    BPL start_high")
    a("    LDA #$40                  ; DMA on, 160A")
    a("    STA CTRL")
    a("main:")
    a("    BIT MSTAT")
    a("    BMI main                  ; wait for the picture")
    a("wait_vblank:")
    a("    BIT MSTAT")
    a("    BPL wait_vblank")
    a("    LDA #$00")
    a("    STA ROW")
    a("    JMP main")
    a("")
    a("; One interrupt per row: hue ROW, luminance 0-15 into palettes 0-5")
    a("; (colours 1-3 of each; the 16th is P5C1).")
    a("nmi:")
    a("    PHA")
    a("    LDA ROW")
    a("    ASL")
    a("    ASL")
    a("    ASL")
    a("    ASL")
    a("    CLC")
    for i, r in enumerate(regs):
        if i:
            a("    ADC #$01")
        a("    STA $%02X" % r)
    a("    INC ROW")
    a("    PLA")
    a("irq:")
    a("    RTI")
    a("")
    a("dl_empty:")
    a("    .byte $00,$00")
    a("dl_bar:")
    a("    .byte $10,$EC,$%02X,$00     ; palette 7, 20 bytes, x 0" % (GFX_PAGE + 1))
    a("    .byte $10,$EC,$%02X,$50     ; x 80" % (GFX_PAGE + 1))
    a("    .byte $00,$00")
    a("dl_row:")
    for c in range(16):
        a("    .byte $%02X,$%02X,$%02X,$%02X     ; luminance %X: palette %d colour %d, x %d"
          % (2 * (c % 3), ((c // 3) << 5) | 30, GFX_PAGE, 10 * c + 1, c, c // 3, c % 3 + 1, 10 * c + 1))
    a("    .byte $00,$00")
    a("")
    a("dll:")

    def blank(n):
        while n > 0:
            k = min(n, 16)
            a("    .byte $%02X,>dl_empty,<dl_empty" % (k - 1))
            n -= k
    blank(top)
    a("    .byte $03,>dl_bar,<dl_bar")
    for r in range(16):
        a("    .byte $82,>dl_empty,<dl_empty    ; row %X: 3 blank lines, interrupt" % r)
        a("    .byte $07,>dl_row,<dl_row")
    a("    .byte $02,>dl_empty,<dl_empty")
    a("    .byte $03,>dl_bar,<dl_bar")
    blank(160)
    a("")
    a("code_end:")
    a("    .res $FF80-code_end,$FF")
    a("    .res $78,$FF                  ; the signature ($FF80-$FFF7)")
    a("    .byte $FF                     ; $FFF8: region byte")
    a("    .byte $C7                     ; $FFF9: hashed from $C000, no rainbow")
    a("    .word nmi")
    a("    .word reset")
    a("    .word irq")
    return "\n".join(L) + "\n"


def a78_header(size, title, pal):
    h = bytearray(128)
    h[0] = 1
    h[1:10] = b"ATARI7800"
    t = title.encode("latin1")[:32]
    h[17:17 + len(t)] = t
    h[49:53] = struct.pack(">I", size)
    h[53:55] = struct.pack(">H", 0x0000)      # linear, no mapper
    h[55] = 1                                 # joysticks
    h[56] = 1
    h[57] = 1 if pal else 0
    h[100:128] = b"ACTUAL CART DATA STARTS HERE"
    return bytes(h)


def build(outdir):
    import asm
    import sign7800
    os.makedirs(outdir, exist_ok=True)
    made = []
    for pal in (False, True):
        tag = "pal" if pal else "ntsc"
        src = source_2600(pal)
        open(os.path.join(outdir, "colortest-2600-%s.asm" % tag), "w").write(src)
        rom = asm.Assembler().assemble(src.splitlines())
        assert len(rom) == 0x1000, len(rom)
        path = os.path.join(outdir, "colortest-2600-%s.a26" % tag)
        open(path, "wb").write(rom)
        made.append(path)

        src = source_7800(pal)
        open(os.path.join(outdir, "colortest-7800-%s.asm" % tag), "w").write(src)
        rom = asm.Assembler().assemble(src.splitlines())
        assert len(rom) == 0x4000, len(rom)
        if not pal:
            rom = sign7800.signed(rom)        # PAL consoles check no signature
            assert sign7800.verify(rom)
        title = "Colour test %s" % tag.upper()
        path = os.path.join(outdir, "colortest-7800-%s.a78" % tag)
        open(path, "wb").write(a78_header(len(rom), title, pal) + rom)
        open(path[:-4] + ".bin", "wb").write(rom)
        made.append(path)
    return made


# -------------------------------------------------------------------- shoot
SHOOT_LUA = """
local f = 0
emu.register_frame_done(function()
  f = f + 1
  if f == 240 then manager.machine.video:snapshot() end
  if f >= 241 then manager.machine:exit() end
end)
"""


def shoot(outdir, mame, rompath=None, bios=None):
    """MAME's picture of each cartridge, at its native size: mame-<machine>.png."""
    import capture
    exe = capture.find_mame(mame)
    if not exe:
        sys.exit("MAME was not found: pass --mame or set A7800_MAME")
    rompath = rompath or os.environ.get("A7800_ROMPATH")
    shots = []
    with tempfile.TemporaryDirectory() as tmp:
        lua = os.path.join(tmp, "shoot.lua")
        open(lua, "w").write(SHOOT_LUA)
        for name, (_, fname, system) in MACHINES.items():
            cart = os.path.abspath(os.path.join(outdir, fname))
            if not os.path.isfile(cart):
                sys.exit("%s is missing: run `colortest.py build` first" % cart)
            snapdir = os.path.join(tmp, name)
            cmd = [exe, system, "-cart", cart, "-skip_gameinfo", "-nothrottle",
                   "-sound", "none", "-video", "none", "-window",
                   "-snapshot_directory", snapdir, "-snapname", "shot",
                   "-snapview", "native", "-autoboot_script", lua,
                   "-cfg_directory", os.path.join(tmp, "cfg"),
                   "-nvram_directory", os.path.join(tmp, "nvram")]
            if system.startswith("a7800"):
                cmd += capture.bios_args(bios)
            if rompath:
                cmd += ["-rompath", rompath]
            env = dict(os.environ, SDL_VIDEODRIVER=os.environ.get("SDL_VIDEODRIVER", "dummy"))
            r = subprocess.run(cmd, capture_output=True, text=True, env=env, timeout=120)
            png = os.path.join(snapdir, "shot.png")
            if not os.path.isfile(png):
                sys.exit("MAME made no picture for %s:\n%s%s" % (name, r.stdout, r.stderr))
            out = os.path.join(outdir, "mame-%s.png" % name)
            os.replace(png, out)
            shots.append(out)
    return shots


# ------------------------------------------------------------------ compare
def _is_bar(px):
    r, g, b = px[:3]
    return min(r, g, b) >= 140 and max(r, g, b) - min(r, g, b) <= 60


def find_grid(img):
    """(top, bottom, left, right) of the grid, from its two white bars."""
    w, h = img.size
    px = img.load()
    runs = []           # (y, start, end) of the longest bar-coloured run of each row
    for y in range(h):
        best = (0, 0)
        start = None
        for x in range(w + 1):
            on = x < w and _is_bar(px[x, y])
            if on and start is None:
                start = x
            elif not on and start is not None:
                if x - start > best[1] - best[0]:
                    best = (start, x)
                start = None
        if best[1] - best[0] >= 0.3 * w:
            runs.append((y, best[0], best[1]))
    if not runs:
        raise ValueError("no white bars: is this a screenshot of the colour test?")
    # group into bars: consecutive rows
    bars = [[runs[0]]]
    for r in runs[1:]:
        if r[0] == bars[-1][-1][0] + 1:
            bars[-1].append(r)
        else:
            bars.append([r])
    if len(bars) < 2:
        raise ValueError("found one white bar, not two")
    upper, lower = bars[0], bars[-1]
    top = upper[0][0]
    bottom = lower[-1][0] + 1
    ends = sorted(r[1] for r in upper + lower), sorted(r[2] for r in upper + lower)
    left = ends[0][len(ends[0]) // 2]
    right = ends[1][len(ends[1]) // 2]
    return top, bottom, left, right


def sample(img, columns):
    """{code: (r, g, b)} read from the middle of every cell."""
    top, bottom, left, right = find_grid(img)
    g = GEOMETRY
    yscale = (bottom - top) / g["total"]
    cw = (right - left) / columns
    px = img.load()
    out = {}
    for row in range(16):
        y0 = top + (g["row_first"] + g["row_pitch"] * row + 1) * yscale
        y1 = top + (g["row_first"] + g["row_pitch"] * row + g["row_lines"] - 1) * yscale
        for col in range(columns):
            x0 = left + (col + 0.3) * cw
            x1 = left + (col + 0.7) * cw
            ys = range(int(round(y0)), max(int(round(y1)), int(round(y0)) + 1))
            xs = range(int(round(x0)), max(int(round(x1)), int(round(x0)) + 1))
            chans = [sorted(px[x, y][i] for y in ys for x in xs) for i in range(3)]
            rgb = tuple(c[len(c) // 2] for c in chans)
            code = (row << 4) | (col * 16 // columns)
            out[code] = rgb
    return out


def _lab(rgb):
    def lin(c):
        c /= 255.0
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (lin(c) for c in rgb)
    x = (0.4124 * r + 0.3576 * g + 0.1805 * b) / 0.95047
    y = (0.2126 * r + 0.7152 * g + 0.0722 * b)
    z = (0.0193 * r + 0.1192 * g + 0.9505 * b) / 1.08883
    f = lambda t: t ** (1 / 3) if t > 0.008856 else 7.787 * t + 16 / 116
    return 116 * f(y) - 16, 500 * (f(x) - f(y)), 200 * (f(y) - f(z))


def delta_e(a, b):
    """CIE76: about 2 is just noticeable side by side, 10 is plainly another colour."""
    la, lb = _lab(a), _lab(b)
    return sum((p - q) ** 2 for p, q in zip(la, lb)) ** 0.5


def guess_columns(img):
    """8 for a 2600 screenshot, 16 for a 7800 one: the 7800's cells have black gaps."""
    top, bottom, left, right = find_grid(img)
    px = img.load()
    y = int(top + (GEOMETRY["row_first"] + 3) * (bottom - top) / GEOMETRY["total"])
    # hue 0 row: count dark gaps between the light cells on the right half
    dark = 0
    prev = None
    for x in range(left + (right - left) // 2, right):
        d = max(px[x, y][:3]) < 40
        if d and prev is False:
            dark += 1
        prev = d
    return 16 if dark >= 3 else 8


def compare(ref_path, other_path, out_png=None, out_json=None, columns=None):
    from PIL import Image, ImageDraw
    ref = Image.open(ref_path).convert("RGB")
    other = Image.open(other_path).convert("RGB")
    columns = columns or guess_columns(other)
    a = sample(ref, columns)
    b = sample(other, columns)
    rows = []
    for code in sorted(a):
        rows.append((code, a[code], b[code], delta_e(a[code], b[code])))
    print("code  reference        other            delta E")
    for code, ra, rb, d in rows:
        print("$%02X   #%02X%02X%02X (%3d,%3d,%3d)  #%02X%02X%02X (%3d,%3d,%3d)  %5.1f"
              % ((code,) + ra + ra + rb + rb + (d,)))
    ds = [d for *_, d in rows]
    print()
    print("mean delta E %.1f, worst %.1f; %d of %d cells over 10 (plainly different)"
          % (sum(ds) / len(ds), max(ds), sum(d > 10 for d in ds), len(ds)))
    worst = sorted(rows, key=lambda r: -r[3])[:10]
    print("worst: " + ", ".join("$%02X (%.0f)" % (c, d) for c, _, _, d in worst))

    if out_json:
        json.dump({"$%02X" % c: "#%02X%02X%02X" % ra for c, ra, _, _ in rows},
                  open(out_json, "w"), indent=1)
    if out_png:
        cell = 48
        img = Image.new("RGB", (columns * cell, 16 * cell + 20), (0, 0, 0))
        d = ImageDraw.Draw(img)
        d.text((4, 16 * cell + 4), "left: %s   right: %s"
               % (os.path.basename(ref_path), os.path.basename(other_path)), fill=(255, 255, 255))
        for code, ra, rb, de in rows:
            r, c = code >> 4, (code & 15) * columns // 16
            x, y = c * cell, r * cell
            d.rectangle([x, y, x + cell // 2 - 1, y + cell - 1], fill=ra)
            d.rectangle([x + cell // 2, y, x + cell - 1, y + cell - 1], fill=rb)
            ink = (0, 0, 0) if _lab(ra)[0] > 55 else (255, 255, 255)
            d.text((x + 2, y + 2), "%02X" % code, fill=ink)
            if de > 10:
                d.text((x + 2, y + cell - 12), "%.0f" % de, fill=ink)
        img.save(out_png)
        print("wrote", out_png)
    return rows


